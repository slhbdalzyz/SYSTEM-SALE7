export interface LibraryItem { name: string; category: string; unit: string; weighted: boolean; packUnit?: string; packQty?: number }

/** The library's items for a kind of shop ("other" gets the grocery shelves), department by department. */
export function libraryFor(businessType: string | null | undefined): LibraryItem[] {
  const shelf = LIBRARY[businessType ?? "grocery"] ?? GROCERY;
  return Object.entries(shelf).flatMap(([category, rows]) => rows.map((row) => {
    const weighted = row.startsWith("~");
    const [name, unit, packUnit, qty] = row.replace(/^~/, "").split(";");
    return { name, category, unit: weighted ? "كيلو" : unit || "حبة", weighted, ...(packUnit && Number(qty) > 1 ? { packUnit, packQty: Number(qty) } : {}) };
  }));
}

